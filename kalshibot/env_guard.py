"""Production lockout.

This module exists for one reason: to make it structurally impossible for
this bot to send an order to Kalshi production.

The defence is layered on purpose. Any one check could be bypassed by a
careless edit; all of them together cannot be bypassed by accident.

  1. An allowlist of demo hostnames. Anything else is refused.
  2. A denylist of known production hostnames, checked independently.
  3. assert_demo() called at import time by the execution client.
  4. assert_demo() called again inside every order-placing function, with the
     URL that is about to be used.
  5. The execution client's method is named place_demo_order(), so a generic
     place_order() call is an AttributeError rather than a live trade.

If you ever genuinely want production, you do not edit this file. You write a
different program, deliberately, with its own risk review.
"""
from __future__ import annotations

import os
import re
from urllib.parse import urlparse

DEMO_HOSTS = {
    "external-api.demo.kalshi.co",
    "external-api-ws.demo.kalshi.co",
    "demo-api.kalshi.co",
}

PRODUCTION_HOSTS = {
    "external-api.kalshi.com",
    "external-api-ws.kalshi.com",
    "api.elections.kalshi.com",
    "trading-api.kalshi.com",
    "api.kalshi.com",
    "kalshi.com",
    "www.kalshi.com",
}

#: Any host that is a kalshi domain but does NOT contain "demo" is suspect.
_KALSHI_DOMAIN = re.compile(r"(^|\.)kalshi\.(com|co)$", re.I)

#: Loopback only, and only when the integration-test flag is set.
#:
#: This can never unlock a public host. The production denylist is checked
#: first and unconditionally, and the allowance is limited to addresses that
#: are by definition this machine. A mock exchange on 127.0.0.1 is not Kalshi,
#: so nothing here can put an order in front of real money.
_LOOPBACK = {"127.0.0.1", "localhost", "::1", "[::1]"}


def _loopback_allowed_for_tests(host: str) -> bool:
    return (os.getenv("KALSHIBOT_ALLOW_LOOPBACK_FOR_TESTS") == "1"
            and host in _LOOPBACK)


class ProductionBlocked(RuntimeError):
    """Raised whenever anything smells like production. Never caught."""


def host_of(url: str) -> str:
    parsed = urlparse(url if "//" in url else f"https://{url}")
    return (parsed.hostname or "").lower()


def is_demo_host(url: str) -> bool:
    host = host_of(url)
    if not host:
        return False
    # Production is checked first and unconditionally. No flag bypasses this.
    if host in PRODUCTION_HOSTS:
        return False
    if host in DEMO_HOSTS:
        return True
    if _loopback_allowed_for_tests(host):
        return True
    # Unknown kalshi host: only trust it if "demo" is in the hostname.
    if _KALSHI_DOMAIN.search(host):
        return "demo" in host
    return False


def assert_demo_url(url: str, what: str = "request") -> None:
    host = host_of(url)
    if host in PRODUCTION_HOSTS:
        raise ProductionBlocked(
            f"REFUSED: {what} targets the Kalshi PRODUCTION host {host!r}. "
            "This build is demo-only and will not place real-money orders."
        )
    if not is_demo_host(url):
        raise ProductionBlocked(
            f"REFUSED: {what} targets {host!r}, which is not a recognised Kalshi "
            f"demo host. Allowed: {sorted(DEMO_HOSTS)}"
        )


#: The ONLY production paths this build may read, and only with GET.
#:
#: Kalshi's market data is public - "No authentication headers are required
#: for the endpoints in this guide" - so reading a live order book needs no
#: API key, no signature, and no account. That matters: the reason to look at
#: production at all is that demo books are synthetic, so every fill-quality
#: number measured on demo is measured against a fiction. This lets the paper
#: engine price against the real book without a credential existing anywhere.
#:
#: Nothing on this list can move money. There is no portfolio path, no order
#: path, no balance path, and the client that uses it sends no auth header and
#: refuses any method other than GET.
PUBLIC_MARKET_DATA_PATHS = (
    "/markets",
    "/events",
    "/series",
)


def is_public_market_data_path(path: str) -> bool:
    """A read-only market data path, and nothing that touches an account."""
    p = "/" + (path or "").split("?")[0].strip("/")
    if "/portfolio" in p or "/orders" in p or "/balance" in p or "/fills" in p:
        return False
    return any(p == base or p.startswith(base + "/")
               for base in PUBLIC_MARKET_DATA_PATHS)


def assert_public_market_data(url: str, path: str, method: str = "GET") -> None:
    """Permit a production READ of public market data. Nothing else.

    This is the one place in this codebase where a production hostname is
    allowed, and it is allowed for exactly three path prefixes, exactly one
    HTTP method, and only for a client that carries no credentials.

    It does not weaken `assert_demo_url`, which every trading path still calls
    and which still refuses production unconditionally. An order cannot reach
    production through here because no path on the list accepts one.
    """
    if (method or "").upper() != "GET":
        raise ProductionBlocked(
            f"REFUSED: {method} to {path!r}. Public market data is read-only; "
            "only GET is permitted, and orders never come this way."
        )
    if not is_public_market_data_path(path):
        raise ProductionBlocked(
            f"REFUSED: {path!r} is not public market data. Allowed prefixes: "
            f"{list(PUBLIC_MARKET_DATA_PATHS)}. Anything touching a portfolio, "
            "an order, a fill or a balance is refused here whatever the host."
        )
    host = host_of(url)
    if not _KALSHI_DOMAIN.search(host) and not _loopback_allowed_for_tests(host):
        raise ProductionBlocked(
            f"REFUSED: {host!r} is not a Kalshi host.")


def assert_live_books_are_paper_only(mode: str, book_source: str) -> None:
    """Live books may only ever be paired with paper trading.

    Reading the real book is harmless on its own - it is public data and no
    credential exists. What would NOT be harmless is a build that prices
    against production depth and then sends orders somewhere, because the
    numbers would look right while describing a different market. So the two
    settings are locked together: live books require PAPER, and anything else
    refuses to start rather than running a half-sensible hybrid.
    """
    if (book_source or "demo").strip().lower() != "live":
        return
    if (mode or "").strip().upper() != "PAPER":
        raise ProductionBlocked(
            f"REFUSED: execution.paper_book_source is 'live' but the mode is "
            f"{mode!r}. Live order books are for measuring what a fill would "
            "have cost, and may only be used with mode: paper. Set the mode "
            "to paper, or the book source back to demo."
        )


def assert_demo_environment(env: str | None = None) -> str:
    env = (env if env is not None else os.getenv("KALSHI_ENV", "")).strip().lower()
    if env != "demo":
        raise ProductionBlocked(
            f"REFUSED: KALSHI_ENV is {env!r}. This build only runs against the "
            "Kalshi demo environment. Set KALSHI_ENV=demo."
        )
    return env


def assert_trading_allowed(env: str, rest_url: str, what: str = "order") -> None:
    """The single call every order path must make. Both checks, every time."""
    assert_demo_environment(env)
    assert_demo_url(rest_url, what)


def describe_guard() -> str:
    return (
        "Production lockout ACTIVE\n"
        f"  demo hosts allowed   : {', '.join(sorted(DEMO_HOSTS))}\n"
        f"  production hosts     : blocked ({len(PRODUCTION_HOSTS)} known)\n"
        "  unknown kalshi hosts : blocked unless the hostname contains 'demo'\n"
        "  order entry point    : place_demo_order() only\n"
        "  production reads     : public market data only, GET only, no "
        "credential, no portfolio/order/fill/balance path"
    )
